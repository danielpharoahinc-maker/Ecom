-- Proof reminders. Run once in Supabase > SQL Editor, after schema.sql.
-- Switches on two free Supabase add-ons for scheduling and web requests.
create extension if not exists pg_cron;
create extension if not exists pg_net;

-- What each person wants to be reminded about, and where to send it.
create table public.reminders (
  user_id         uuid primary key default auth.uid() references auth.users on delete cascade,
  tz              text not null default 'Africa/Johannesburg',
  times           text[] not null default '{}',          -- 'HH:MM' proof-time check-ins
  streak_saver    boolean not null default true,         -- 20:00 if nothing posted today
  plan_items      jsonb not null default '[]'::jsonb,    -- today's timed plan items [{at:'06:30', text:'Gym'}]
  plan_day        date,
  last_posted_on  date,                                  -- set by the app when you post
  subscription    jsonb,                                 -- the phone's push address
  sent            jsonb not null default '{}'::jsonb,    -- what was already sent today
  updated_at      timestamptz not null default now()
);

alter table public.reminders enable row level security;
revoke all on public.reminders from anon;
create policy "own reminders" on public.reminders for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());
-- The app may not touch the 'sent' log; only the server does.
revoke insert, update on public.reminders from authenticated;
grant insert (user_id, tz, times, streak_saver, plan_items, plan_day, last_posted_on, subscription, updated_at) on public.reminders to authenticated;
grant update (tz, times, streak_saver, plan_items, plan_day, last_posted_on, subscription, updated_at) on public.reminders to authenticated;

-- Push keys and the cron key. Generated by the server on first use; no app access at all.
create table public.push_keys (
  id          int primary key default 1 check (id = 1),
  public_key  text not null,
  private_key text not null,
  cron_key    text not null default encode(gen_random_bytes(24), 'hex')
);
alter table public.push_keys enable row level security;
revoke all on public.push_keys from anon, authenticated;

-- Every 5 minutes, ask the server to send whatever is due.
-- (Replace YOUR-PROJECT-REF if your project address is different.)
select cron.schedule('proof-reminders', '*/5 * * * *', $$
  select net.http_post(
    url := 'https://kfnetfsyvhyysjjhpwue.supabase.co/functions/v1/push',
    headers := jsonb_build_object('Content-Type', 'application/json',
                                  'x-cron-key', (select cron_key from public.push_keys where id = 1)),
    body := '{"action":"send"}'::jsonb
  );
$$);
